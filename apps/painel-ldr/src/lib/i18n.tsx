const DICTS: Record<Locale, Dict> = { pt, en, fr, es };
const STORAGE_KEY = "ldr.locale";

type Ctx = { locale: Locale; setLocale: (l: Locale) => void; t: (key: string) => string };

const I18nContext = createContext<Ctx>({ locale: "pt", setLocale: () => {}, t: (k) => pt[k] ?? k });

function detect(): Locale {
  if (typeof window === "undefined") return "pt";
  const saved = window.localStorage.getItem(STORAGE_KEY);
  if (saved && (LOCALES as readonly string[]).includes(saved)) return saved as Locale;
  const nav = window.navigator.language?.slice(0, 2).toLowerCase();
  return (LOCALES as readonly string[]).includes(nav ?? "") ? (nav as Locale) : "pt";
}

export function I18nProvider({ children }: { children: ReactNode }) {
  // Hidrata sempre em PT e ajusta após o mount (evita mismatch de SSR).
  const [locale, setLocaleState] = useState<Locale>("pt");

  useEffect(() => {
    setLocaleState(detect());
  }, []);

  const setLocale = useCallback((l: Locale) => {
    setLocaleState(l);
    try {
      window.localStorage.setItem(STORAGE_KEY, l);
    } catch {
      /* armazenamento indisponível */
    }
  }, []);

  const value = useMemo<Ctx>(
    () => ({
      locale,
      setLocale,
      t: (key: string) => DICTS[locale][key] ?? pt[key] ?? key,
    }),
    [locale, setLocale],
  );

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n() {
  return useContext(I18nContext);
}

